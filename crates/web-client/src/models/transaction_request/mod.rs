/// Specifies a transaction request that can be executed by an account.
///
/// A request contains information about input notes to be consumed by the transaction (if any),
/// blocks that must be available to the transaction, the transaction script to execute (if any),
/// and notes expected to be generated by this transaction or a later transaction.
#[derive(Clone)]
#[js_export]
pub struct TransactionRequest(NativeTransactionRequest);

#[js_export]
impl TransactionRequest {
    /// Serializes the transaction request into bytes.
    pub fn serialize(&self) -> JsBytes {
        encode_proto(&self.0)
    }

    /// Deserializes a transaction request from bytes.
    pub fn deserialize(bytes: JsBytes) -> Result<TransactionRequest, JsErr> {
        decode_proto::<NativeTransactionRequest>(&bytes).map(TransactionRequest)
    }

    /// Returns whether `other` has the same fields as this request.
    ///
    /// This compares the request's structure, not its serialized bytes. Bytes that list the same
    /// fields or Merkle store nodes in another order decode to an equal request, so two requests
    /// with every field equal can differ in bytes. Use this to check that a request kept its
    /// fields through a copy or a transport.
    pub fn equals(&self, other: &TransactionRequest) -> bool {
        self.0 == other.0
    }

    /// Returns output notes created by the sender account.
    #[js_export(js_name = "expectedOutputOwnNotes")]
    pub fn expected_output_own_notes(&self) -> Result<Vec<Note>, JsErr> {
        let native_notes: Vec<NativeNote> = self.0.expected_output_own_notes();
        let notes: Vec<Note> = native_notes.into_iter().map(Into::into).collect();
        Ok(notes)
    }

    /// Returns notes expected to be created in subsequent executions.
    #[js_export(js_name = "expectedFutureNotes")]
    pub fn expected_future_notes(&self) -> Result<Vec<NoteDetailsAndTag>, JsErr> {
        self.0
            .expected_future_notes()
            .cloned() // This converts &(T, U) to (T, U)
            .map(|(note_details, note_tag)| {
                Ok(NoteDetailsAndTag::new(note_details.into(), note_tag.into()))
            })
            .collect::<Result<Vec<NoteDetailsAndTag>, _>>()
    }

    /// Whether execution skips input notes that are no longer consumable instead of failing.
    /// Skipping screens at most 20 input notes and fails with `invalid input note count` above
    /// that.
    #[js_export(js_name = "ignoresInvalidInputNotes")]
    pub fn ignores_invalid_input_notes(&self) -> bool {
        self.0.ignore_invalid_input_notes()
    }

    /// Returns the note scripts declared for the network to execute, standard scripts included.
    /// Only registration ignores the standard ones.
    #[js_export(js_name = "expectedNtxScripts")]
    pub fn expected_ntx_scripts(&self) -> Vec<NoteScript> {
        self.0.expected_ntx_scripts().iter().map(Into::into).collect()
    }

    /// Returns the new account code carried for an account code upgrade, if any.
    #[js_export(js_name = "accountCodeUpgrade")]
    pub fn account_code_upgrade(&self) -> Option<AccountCode> {
        self.0.account_code_upgrade().map(|upgrade| upgrade.code().into())
    }

    /// Returns the transaction script argument if present.
    #[js_export(js_name = "scriptArg")]
    pub fn script_arg(&self) -> Option<Word> {
        match self.0.transaction_script() {
            RequestTransactionScript::Custom { arg, .. } => Some((*arg).into()),
            _ => None,
        }
    }

    /// Returns the authentication argument if present.
    ///
    /// A request built by a builder that called neither `withAuthArgs` nor `withFeeConversionSalt`
    /// has none: the client commits fee conversion info into the auth args while preparing the
    /// transaction, which is after this can observe it.
    ///
    /// There is deliberately no setter here. An auth argument can only be set through
    /// `TransactionRequestBuilder.withAuthArgs`, because miden-client keeps it mutually exclusive
    /// with the fee conversion salt and enforces that on the builder — a setter on a finished
    /// request would sit outside that exclusion.
    #[js_export(js_name = "authArg")]
    pub fn auth_arg(&self) -> Option<Word> {
        match self.0.auth_args() {
            RequestAuthArgs::Explicit(arg) => Some((*arg).into()),
            _ => None,
        }
    }

    /// Returns the fee conversion salt this request declares, if any.
    ///
    /// Declared through `TransactionRequestBuilder.withFeeConversionSalt`, and carried through
    /// serialization, so a request transported to a co-signer still names the salt its summary
    /// was derived under. `undefined` means none was declared: miden-client then commits the
    /// chain's native conversion info under its own fixed default salt, which is what every
    /// account other than a multisig wants.
    ///
    /// Mutually exclusive with `authArg` — setting both fails when building the request.
    #[js_export(js_name = "feeConversionSalt")]
    pub fn fee_conversion_salt(&self) -> Option<Word> {
        match self.0.auth_args() {
            RequestAuthArgs::DefaultWithSalt(salt) => Some((*salt).into()),
            _ => None,
        }
    }

    /// Returns the Merkle store nodes added through `extendMerkleStore`, in no particular order.
    /// The empty-subtree nodes every store starts with are left out.
    #[js_export(js_name = "merkleStoreInnerNodes")]
    pub fn merkle_store_inner_nodes(&self) -> Vec<InnerNodeInfo> {
        let empty = NativeMerkleStore::new();
        self.0
            .merkle_store()
            .inner_nodes()
            .filter(|node| empty.get_node(node.value, NodeIndex::root()).is_err())
            .map(Into::into)
            .collect()
    }

    /// Returns a copy of the advice map carried by this request.
    #[js_export(js_name = "adviceMap")]
    pub fn advice_map(&self) -> AdviceMap {
        self.0.advice_map().into()
    }

    /// Returns a copy of this request with `advice_map` merged into its advice map.
    ///
    /// Entries are merged with last-write-wins semantics: a key already present in the request is
    /// overwritten by the value from `advice_map`. Use this to inject advice (e.g. a signature
    /// produced by an external signer) after the request has already been built.
    #[js_export(js_name = "extendAdviceMap")]
    pub fn extend_advice_map(&self, advice_map: &AdviceMap) -> TransactionRequest {
        let native_advice_map: NativeAdviceMap = advice_map.into();
        let mut native_request = self.0.clone();
        native_request
            .advice_map_mut()
            .extend(native_advice_map.iter().map(|(key, value)| (*key, value.clone())));
        native_request.into()
    }

    /// Returns a copy of this request with the auth arg set to the commitment of `preimage`, and
    /// with `preimage` added to the advice map under that commitment.
    ///
    /// This mirrors `TransactionRequest::with_auth_args` of miden-client. Use it for auth
    /// components that load their auth args from the advice map, for example a multisig. The
    /// commitment is the Eidos hash of `preimage`, the same commitment that `SequentialCommit`
    /// computes, so the auth arg and its advice-map entry always agree.
    ///
    /// The new auth args replace the previous auth arg and the declared fee conversion salt. An
    /// existing advice-map entry under the same key is overwritten. Every other field of the
    /// request stays the same. miden-client tracks the bound block of multisig auth args when it
    /// executes the request. The request does not declare that block as a block number, so
    /// `blockNumbers()` does not return it.
    ///
    /// The `Felt`s are consumed by the call in the browser build: they are moved across the WASM
    /// boundary, so read what you need from them before the call and pass fresh ones to another
    /// call. A spent `Felt` fails with "null pointer passed to rust".
    #[js_export(js_name = "withAuthArgs")]
    pub fn with_auth_args(&self, preimage: Vec<Felt>) -> TransactionRequest {
        let preimage = AuthArgsPreimage(preimage.into_iter().map(NativeFelt::from).collect());
        self.0.clone().with_auth_args(&preimage).into()
    }

    /// Returns a copy of this request whose multisig auth args carry a max fee, and the summary
    /// that binds it.
    ///
    /// The summary of a multisig binds a max fee. Auth args without one make the auth procedure
    /// estimate the fee on each execution, so `summary`, the summary of an unsigned execution of
    /// this request, binds the estimate of that execution. This scales the max fee that `summary`
    /// binds by `fee_margin_percent`, rounded up, and sets the result on the auth args and on the
    /// summary: 100 keeps the value and 150 adds half of it. Executing the returned request
    /// reproduces the returned summary, so the approvers sign that summary and no second
    /// execution is needed. The signed execution then pays any fee up to the max fee, also when
    /// the fee of the chain has changed.
    ///
    /// A max fee of zero means that the auth procedure estimates the fee. On a chain that charges
    /// no fee the estimate is zero, and this returns an equal request and summary.
    ///
    /// Every other field of the request stays the same.
    ///
    /// # Errors
    /// - `AUTH_ARGS_NOT_MULTISIG` if this request has no auth argument, or its auth args are not
    ///   multisig auth args. `feeAwareTransactionRequestBuilder` and `withFeeAwareAuth` set them
    ///   for a multisig account.
    /// - If `summary` does not bind the bound block, the approval expiration and the salt of the
    ///   auth args. It is then the summary of another request.
    /// - If `fee_margin_percent` is zero, or the scaled max fee is not a valid amount.
    #[js_export(js_name = "withEstimatedMaxFee")]
    pub fn with_estimated_max_fee(
        &self,
        summary: &TransactionSummary,
        fee_margin_percent: u32,
    ) -> Result<EstimatedMaxFee, JsErr> {
        const CONTEXT: &str = "failed to set the estimated max fee";
        EstimatedMaxFee::new(&self.0, &summary.into(), fee_margin_percent).map_err(
            |err| match err {
                MaxFeeError::NotMultisigAuthArgs(_) => {
                    from_str_err_with_code(&format!("{CONTEXT}: {err}"), "AUTH_ARGS_NOT_MULTISIG")
                },
                MaxFeeError::SummaryMismatch(_) | MaxFeeError::InvalidMaxFee(_) => {
                    js_error_with_context(err, CONTEXT)
                },
            },
        )
    }
}

/// Auth args given as their preimage. The commitment is the default `SequentialCommit` hash.
struct AuthArgsPreimage(Vec<NativeFelt>);

impl SequentialCommit for AuthArgsPreimage {
    type Commitment = NativeWord;

    fn to_elements(&self) -> Vec<NativeFelt> {
        self.0.clone()
    }
}

// `blockNumbers` is split by platform only to return `number[]` on both. napi maps `Vec<u32>` to
// `number[]`; wasm-bindgen would return a `Uint32Array`.
#[cfg(feature = "browser")]
#[wasm_bindgen::prelude::wasm_bindgen]
impl TransactionRequest {
    /// Returns the blocks the transaction must be able to authenticate, in ascending order.
    ///
    /// Declared through `TransactionRequestBuilder.withBlockNumbers`, or by
    /// `feeAwareTransactionRequestBuilder` for a multisig, and carried through serialization.
    #[wasm_bindgen(js_name = "blockNumbers", unchecked_return_type = "number[]")]
    pub fn block_numbers(&self) -> js_sys::Array {
        self.native_block_numbers().map(wasm_bindgen::JsValue::from).collect()
    }
}

#[cfg(feature = "nodejs")]
#[napi_derive::napi]
impl TransactionRequest {
    /// Returns the blocks the transaction must be able to authenticate, in ascending order.
    ///
    /// Declared through `TransactionRequestBuilder.withBlockNumbers`, or by
    /// `feeAwareTransactionRequestBuilder` for a multisig, and carried through serialization.
    #[napi(js_name = "blockNumbers")]
    pub fn block_numbers(&self) -> Vec<u32> {
        self.native_block_numbers().collect()
    }
}

impl TransactionRequest {
    fn native_block_numbers(&self) -> impl Iterator<Item = u32> + '_ {
        self.0.block_numbers().iter().map(BlockNumber::as_u32)
    }
}

// CONVERSIONS
// ================================================================================================

impl From<TransactionRequest> for NativeTransactionRequest {
    fn from(transaction_request: TransactionRequest) -> Self {
        transaction_request.0
    }
}

impl From<&TransactionRequest> for NativeTransactionRequest {
    fn from(transaction_request: &TransactionRequest) -> Self {
        transaction_request.0.clone()
    }
}

impl From<NativeTransactionRequest> for TransactionRequest {
    fn from(transaction_request: NativeTransactionRequest) -> Self {
        TransactionRequest(transaction_request)
    }
}

impl From<&NativeTransactionRequest> for TransactionRequest {
    fn from(transaction_request: &NativeTransactionRequest) -> Self {
        TransactionRequest(transaction_request.clone())
    }
}
